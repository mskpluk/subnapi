Maybe<LegacyCodecs::Encoding> LegacyCodecs::encodingForName(const QString& name) {
  const QString n = name.trimmed();

  if (n.compare("windows-1250", Qt::CaseInsensitive) == 0)
    return just(Encoding::Windows1250);
  if (n.compare("windows-1257", Qt::CaseInsensitive) == 0)
    return just(Encoding::Windows1257);
  if (n.compare("ISO-8859-2", Qt::CaseInsensitive) == 0)
    return just(Encoding::Iso8859_2);
  if (n.compare("ISO-8859-13", Qt::CaseInsensitive) == 0)
    return just(Encoding::Iso8859_13);
  if (n.compare("ISO-8859-16", Qt::CaseInsensitive) == 0)
    return just(Encoding::Iso8859_16);

  return nothing();
}

QString LegacyCodecs::toUnicode(Encoding encoding, const QByteArray& bytes) {
  const char16_t* highTable = highTableFor(encoding);

  QString result;
  result.reserve(bytes.size());

  for (unsigned char byte : bytes) {
    result.append(byte < 0x80 ? QChar(byte) : QChar(highTable[byte - 0x80]));
  }

  return result;
}

QByteArray LegacyCodecs::fromUnicode(Encoding encoding, const QString& text) {
  const QHash<char16_t, uchar>& reverse = reverseTableFor(encoding);

  QByteArray result;
  result.reserve(text.size());

  for (QChar c : text) {
    if (c.unicode() < 0x80) {
      result.append(static_cast<char>(c.unicode()));
      continue;
    }
    auto it = reverse.constFind(c.unicode());
    result.append(static_cast<char>(it != reverse.constEnd() ? *it : '?'));
  }

  return result;
}
